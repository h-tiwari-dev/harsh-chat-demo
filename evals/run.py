"""python -m evals.run  ->  evals/report.md + evals/report.json (generated from real run results)."""
from __future__ import annotations

import importlib
import json
import os
import sys
import time

from .harness import REGISTRY, run_scenario

MODULES = ("core", "safety", "execution", "memory", "recovery", "limits", "stats")


def load():
    for m in MODULES:
        try:
            importlib.import_module(f"evals.scenarios.{m}")
        except ModuleNotFoundError as e:
            if e.name != f"evals.scenarios.{m}":
                raise


def run_all(only=None):
    load()
    out = []
    for sd in REGISTRY:
        if only and sd.name not in only:
            continue
        t0 = time.perf_counter()
        r = run_scenario(sd)
        r["seconds"] = round(time.perf_counter() - t0, 3)
        out.append(r)
    return out


def _cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def render_md(results) -> str:
    n_ok = sum(r["passed"] for r in results)
    lines = ["# Eval report", "",
             f"Generated by `python -m evals.run` from real runs (offline, scripted LLM, mock marketplace). "
             f"**{n_ok}/{len(results)} scenarios passed.** Every scenario is also checked by the shared invariants "
             "in `evals/invariants.py` (approval-backed mutations, no duplicates, verified success claims, "
             "no forgotten values, no secrets, non-empty terminal message).", "",
             "| scenario | expected | actual | pass/fail | notes |", "|---|---|---|---|---|"]
    for r in results:
        lines.append(f"| {_cell(r['scenario'])} | {_cell(r['expected'])} | {_cell(r['actual'])} | "
                     f"{'PASS' if r['passed'] else 'FAIL'} | {_cell(r['notes'])} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    results = run_all(set(argv or []) or None)
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "report.json"), "w", encoding="utf-8") as f:
        json.dump({"total": len(results), "passed": sum(r["passed"] for r in results), "results": results},
                  f, indent=2, default=str)
    with open(os.path.join(here, "report.md"), "w", encoding="utf-8") as f:
        f.write(render_md(results))
    for r in results:
        print(("PASS " if r["passed"] else "FAIL ") + r["scenario"] + ("" if r["passed"] else "  -> " + r["notes"][-600:]))
    print(f"{sum(r['passed'] for r in results)}/{len(results)} passed")
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
